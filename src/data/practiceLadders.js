function ladder(skill, tasks) {
  return {
    title: "4段階の反復練習",
    intro: `今回くり返す技能は「${skill}」です。各段階は、実際にRで確かめてからチェックしてください。`,
    steps: STAGES.map((stage, index) => ({
      ...stage,
      ...tasks[index],
    })),
  };
}

